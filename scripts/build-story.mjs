// Authoring only. Runtime uses the generated static package and WebCrypto.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createCipheriv, createHash, randomBytes } from "node:crypto";
const root = new URL("../", import.meta.url);
const script = (
  await readFile(
    new URL("docs/story/2026-11-04-lastlight-script.md", root),
    "utf8",
  )
).replaceAll("\r", "");
function passage(marker) {
  const at = script.indexOf(marker);
  if (at < 0) throw new Error("Missing authored scene: " + marker);
  const lines = script.slice(at).split("\n"),
    start = lines.findIndex((l) => l.startsWith(">"));
  const out = [];
  for (const line of lines.slice(start)) {
    if (!line.startsWith(">")) break;
    out.push(line.replace(/^> ?/, ""));
  }
  if (!out.length) throw new Error("Empty scene: " + marker);
  return out.join("\n");
}
const files = {
  "/home/kiwi/archive/revisions.log": passage("归档 A "),
  "/home/kiwi/archive/evacuation.txt": passage("归档 B "),
};
const key = randomBytes(32),
  iv = randomBytes(12),
  cipher = createCipheriv("aes-256-gcm", key, iv);
const encrypted = Buffer.concat([
  cipher.update(JSON.stringify(files), "utf8"),
  cipher.final(),
  cipher.getAuthTag(),
]).toString("base64");
const width = Math.ceil(encrypted.length / 3),
  parts = [
    encrypted.slice(0, width),
    encrypted.slice(width, 2 * width),
    encrypted.slice(2 * width),
  ];
const digest = (text) => createHash("sha256").update(text).digest("hex");
const authority = JSON.stringify(
  {
    format: "kiwi-authority-v1",
    issuer: "kiwi",
    subject: "kwen-home-01",
    scope: ["runtime", "archive", "relay"],
    archive_key: key.toString("base64"),
  },
  null,
  2,
);
const manifest = {
  id: "B17-KIWI-1029",
  subject: "kwen-home-01",
  algorithm: "AES-256-GCM",
  iv: iv.toString("base64"),
  parts: parts.map((p, i) => ({
    part: i + 1,
    sha256: digest(p),
    mirrors: i === 1 ? ["hill-03", "school-02"] : ["hill-03"],
  })),
};
const entries = {
  LETTER: passage("邮件正文如下："),
  TRANSFER_RECORD: passage("归档 C "),
  AUTHORITY_FILE: authority,
  KEY_FINGERPRINT: digest(authority),
  BUNDLE: manifest,
  PARTS: parts,
};
await mkdir(new URL("src/kernel/story/", root), { recursive: true });
await writeFile(
  new URL("src/kernel/story/package.js", root),
  "// Generated by node scripts/build-story.mjs; do not hand-edit.\n" +
    Object.entries(entries)
      .map(
        ([k, v]) =>
          "export const " + k + " = " + JSON.stringify(v, null, 2) + ";",
      )
      .join("\n") +
    "\n",
);
console.log("Authored letter and three authenticated archive parts generated.");
